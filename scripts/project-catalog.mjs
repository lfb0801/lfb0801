export const OWNER = "lfb0801";
export const SITE_REPOSITORY = "lfb0801/lfb0801";

export function publicProjects(repositories) {
  if (!Array.isArray(repositories)) throw new Error("Invalid repository list.");
  if (repositories.some(repo => typeof repo.private !== "boolean" ||
    typeof repo.name !== "string" || typeof repo.owner?.login !== "string")) {
    throw new Error("Incomplete repository metadata; refusing to replace the catalog.");
  }
  return repositories.filter(repo => repo.private === false &&
    repo.owner?.login?.toLowerCase() === OWNER &&
    /^[a-zA-Z0-9_.-]+$/.test(repo.name) && ![".", ".."].includes(repo.name))
    .sort((a, b) => a.name.localeCompare(b.name, "en"));
}

export function readmeMarkdown(readme, repo) {
  if (!readme) return "This repository has no README yet.";
  if (readme.encoding !== "base64" || typeof readme.content !== "string") {
    throw new Error(`Unsupported README response for ${repo.full_name}`);
  }
  const text = Buffer.from(readme.content, "base64").toString("utf8");
  const base = readme.html_url || `${repo.html_url}/blob/${repo.default_branch}/README.md`;
  let fenced = false;
  return text.split("\n").map(line => {
    if (/^\s*(```|~~~)/.test(line)) { fenced = !fenced; return line; }
    if (fenced) return line;
    return line.replace(/(!?\[[^\]]*\]\()([^\s)]+)(\))/g, (match, start, target, end) => {
      if (/^[a-z][a-z\d+.-]*:/i.test(target) || target.startsWith("#")) return match;
      const url = target.startsWith("/") ? new URL(target, "https://github.com") : new URL(target, base);
      return `${start}${url.href}${end}`;
    });
  }).join("\n");
}

export function projectChanges(previous, current) {
  const before = new Set(previous);
  const after = new Set(current);
  return { added: current.filter(name => !before.has(name)), removed: previous.filter(name => !after.has(name)) };
}

export function catalogEntries(projects) {
  const index = ["# Public GitHub projects", "",
    "All public repositories owned by [lfb0801](https://github.com/lfb0801?tab=repositories), refreshed hourly.", "",
    "Open a project for its README and additional notes. Use **Add project notes** to propose more context through an issue and pull request.", ""];
  if (!projects.length) index.push("There are currently no public projects.");
  for (const { repo } of projects) index.push(`- [${repo.name}](/projects/github/${repo.name}.md)`);
  const entries = [
    { path: "/projects/README.md", type: "file", markdown: index.join("\n") + "\n" },
    { path: "/projects/github", type: "directory" },
  ];
  for (const { repo, readme, notes } of projects) {
    const query = new URLSearchParams({ template: "project-notes.yml", title: `Project notes: ${repo.name}`, project: repo.name });
    const markdown = [`# ${repo.name}`, "", `[View on GitHub](${repo.html_url})`, "",
      repo.description || "", "", "## README", "", readmeMarkdown(readme, repo), "",
      ...(notes ? ["## Additional project notes", "", notes, ""] : []),
      `[Add project notes](https://github.com/${SITE_REPOSITORY}/issues/new?${query})`, "",
      "[All projects](/projects/README.md)", ""].join("\n");
    entries.push({ path: `/projects/github/${repo.name}.md`, type: "file", markdown });
  }
  return entries;
}

export function catalogModule(projects) {
  return "// Generated by npm run sync:projects; project notes belong in content/project-notes/.\n" +
    `export const PROJECT_REPOSITORIES = ${JSON.stringify(projects.map(({ repo }) => repo.full_name))};\n` +
    `export const GITHUB_PROJECT_ENTRIES = ${JSON.stringify(catalogEntries(projects))};\n`;
}
